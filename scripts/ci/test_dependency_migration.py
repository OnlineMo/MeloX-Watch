def blob(data):
    return hashlib.sha1(b'blob ' + str(len(data)).encode() + b'\0' + data).hexdigest()


class DependencyMigrationPolicies(unittest.TestCase):
    def setUp(self):
        temporary = tempfile.TemporaryDirectory()
        self.addCleanup(temporary.cleanup)
        self.root = Path(temporary.name)
        self.android = self.root / 'android'
        self.android.mkdir()
        self.committed = {}
        self.current = build.ROOM_SCHEMA_DIRECTORY + '/3.json'
        self.old = build.ROOM_SCHEMA_DIRECTORY + '/1.json'
        for name in (*build.MIGRATION_FROZEN_INPUTS, *build.MIGRATION_TOOLS):
            self.commit(name, b'nonexecuted migration policy fixture\n')
        self.commit('android/' + build.ROOM_DATABASE_SOURCE, b'@Database(version = 3, exportSchema = true)\n')
        self.commit('android/gradle/verification-metadata.xml', XML)
        self.commit('android/app/gradle.lockfile', b'fixture:library:1=oldCompile\nempty=lintChecks\n')
        for version in (1, 2):
            self.commit('android/' + build.ROOM_SCHEMA_DIRECTORY + f'/{version}.json', b'{"old":' + str(version).encode() + b'}\n')
        contexts = (patch.object(build, 'ROOT', self.root), patch.object(build, 'check'),
                    patch.object(build, 'git', side_effect=self.git),
                    patch.object(build, 'properties', return_value={'versionName': '0.0.0', 'versionCode': '0'}),
                    patch.dict(os.environ, ENV, clear=True), patch.object(build, 'run_gradle', side_effect=self.acquire),
                    patch.object(build, 'inspect_apk'), patch.object(build, 'bootstrap_dependencies'),
                    patch.object(build, 'bootstrap_room_schema'))
        for context in contexts:
            value = context.start()
            self.addCleanup(context.stop)
            if getattr(context, 'attribute', None) == 'run_gradle':
                self.process = value
            if getattr(context, 'attribute', None) in ('bootstrap_dependencies', 'bootstrap_room_schema', 'inspect_apk'):
                setattr(self, context.attribute, value)
        self.request = {
            'schema_version': 1, 'kind': build.DEPENDENCY_MIGRATION_KIND, 'owner_login': 'OnlineMo', 'owner_id': 143324986,
            'base_source_sha': BASE, 'current_schema': self.current, 'diagnostic_android_test': False,
            'reviewed_input_hashes': build.schema_checked_input_hashes(),
            'frozen_input_hashes': {name: self.hash(name) for name in build.MIGRATION_FROZEN_INPUTS},
            'migration_tool_hashes': {name: self.hash(name) for name in build.MIGRATION_TOOLS},
            'allowed_dependency_outputs': list(build.DEPENDENCY_REPORT_FILES),
            'runtime_components': {
                'bundledSqliteHost': ['androidx.sqlite', 'sqlite-bundled-jvm', '2.6.2'],
                'robolectricSdk': ['org.robolectric', 'android-all-instrumented', '8.0.0_r4-robolectric-r1-i7'],
                'robolectricSdk30': ['org.robolectric', 'android-all-instrumented', '11-robolectric-6757853-i7'],
            },
        }
        self.save_request()
        self.writer_schema = True

    def write(self, name, data):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        return path

    def commit(self, name, data):
        self.write(name, data)
        self.committed[name] = blob(data)

    def hash(self, name):
        return hashlib.sha256((self.root / name).read_bytes()).hexdigest()

    def save_request(self):
        self.commit(build.DEPENDENCY_MIGRATION_REQUEST, (json.dumps(self.request, indent=2) + '\n').encode())

    def git(self, *args, **kwargs):
        if args == ('rev-parse', 'HEAD'):
            return BUILD
        if args[:2] == ('merge-base', '--is-ancestor'):
            self.assertIn(args[2:], ((BASE, SOURCE), (SOURCE, BUILD)))
            return ''
        if args[:2] == ('ls-tree', '--name-only'):
            self.assertEqual(args[-1], 'android/' + self.current)
            return ''
        if args[:2] in (('rev-parse', '--verify'), ('cat-file', '-e')):
            revision, name = args[2].split(':', 1)
            self.assertIn(revision, ('HEAD', BASE))
            if name not in self.committed:
                raise ValueError('git failed')
            return self.committed[name] if args[0] == 'rev-parse' else ''
        raise AssertionError(args)

    def witness(self):
        records = []
        archive = {'name': 'fixture-library.jar', 'size': 10, 'sha256': 'd' * 64}
        for name, kind in build.dependency_acquire_consumers(self.request['diagnostic_android_test']).items():
            record = {'id': name, 'kind': kind, 'files': [dict(archive)]}
            if kind in ('task-input-archives', 'test-classpath-archives'):
                record.update(file_count=1, directory_count=0, excluded_file_count=0, missing_non_archive_count=0)
            if kind == 'task-input-archives':
                record['outcome'] = 'executed'
            if kind == 'configuration-artifacts':
                record['files'][0]['component'] = self.request['runtime_components'][name.removeprefix(':app:')]
            if kind == 'buildscript-artifacts':
                record['files'][0]['component'] = ['com.android.tools.build', 'gradle', '8.11.1']
            records.append(record)
        configurations = sorted(build.dependency_lock_snapshot((self.android / 'app/gradle.lockfile').read_bytes()))
        return {'schema_version': 1, 'kind': 'dependency-file-acquisition', 'phase': 'migration-acquire',
                'source_sha': SOURCE, 'build_sha': BUILD, 'run_id': 321, 'run_attempt': 2,
                'event': 'pull_request', 'ref': ENV['GITHUB_REF'],
                'writer_tasks': build.dependency_acquire_tasks(self.request['diagnostic_android_test']),
                'test_task_count': 0, 'consumers': sorted(records, key=lambda entry: entry['id']),
                'lock_capture': {'kind': 'all-resolvable-configuration-graphs', 'task': build.LOCK_COLLECTION_TASK,
                                 'status': 'completed', 'configuration_count': len(configurations),
                                 'unresolved_dependency_count': 0, 'project_configurations': {':': [], ':app': configurations}}}

    def acquire(self, command, **kwargs):
        self.assertFalse((self.android / self.current).exists())
        if kwargs['phase'] == 'migration-acquire':
            self.write('android/gradle/verification-metadata.xml', XML.replace(b'</components>', NEW_COMPONENT + b'</components>'))
            lock = b'fixture:library:1=oldCompile\nempty=lintChecks\n'
            for name, parts in self.request['runtime_components'].items():
                lock += (':'.join(parts) + '=' + name + '\n').encode()
            self.write('android/app/gradle.lockfile', lock)
            self.write('android/' + build.ROOM_SCHEMA_REPORT_DIRECTORY + '/' + build.DEPENDENCY_ACQUISITION_FILE,
                       (json.dumps(self.witness()) + '\n').encode())
            if self.writer_schema:
                self.write('android/' + self.current, SCHEMA)
        else:
            self.write('android/' + self.current, SCHEMA)

    def manifest(self):
        return json.loads((self.android / build.ROOM_SCHEMA_REPORT_DIRECTORY / 'bootstrap-manifest.json').read_bytes())

    def complete(self):
        with self.assertRaisesRegex(ValueError, 'not an accepted build'):
            build.build('debug')

    def test_four_calls_acquire_real_consumers_before_three_complete_strict_variants_without_exporting_apk(self):
        with patch.dict(os.environ, {name: 'unlogged-policy-marker' for name in
                                   ('GH_TOKEN', 'GITHUB_TOKEN', 'ACTIONS_RUNTIME_TOKEN', 'ACTIONS_ID_TOKEN_REQUEST_TOKEN')}):
            self.complete()
        self.assertEqual(self.process.call_count, 4)
        calls = self.process.call_args_list
        self.assertEqual([call.kwargs['phase'] for call in calls], list(build.DEPENDENCY_MIGRATION_PHASES))
        self.assertEqual(len({call.kwargs['total_deadline'] for call in calls}), 1)
        command = calls[0].args[0]
        self.assertEqual([part for part in command if part.startswith(':')],
                         build.dependency_acquire_tasks(False) + [build.DEPENDENCY_ACQUISITION_TASK, build.LOCK_COLLECTION_TASK])
        self.assertNotIn(':app:testWatchAndroidDebugUnitTest', command)
        self.assertIn('--rerun-tasks', command)
        self.assertIn('--no-build-cache', command)
        self.assertEqual(command[command.index('--write-verification-metadata') + 1], 'sha256')
        for mode, call in zip(('debug', 'release', 'diagnostic'), calls[1:]):
            self.assertEqual(call.args[0], build.gradle_command(build.gradle_tasks(mode)) + ['--info'])
        for call in calls:
            self.assertEqual(call.kwargs['env']['CI_UNSIGNED_APK'], 'true')
            for name in ('GH_TOKEN', 'GITHUB_TOKEN', 'ACTIONS_RUNTIME_TOKEN', 'ACTIONS_ID_TOKEN_REQUEST_TOKEN'):
                self.assertNotIn(name, call.kwargs['env'])
        self.bootstrap_dependencies.assert_not_called()
        self.bootstrap_room_schema.assert_not_called()
        self.inspect_apk.assert_not_called()
        manifest = self.manifest()
        self.assertEqual(manifest['schema_version'], 4)
        self.assertEqual(manifest['status'], 'generated-unreviewed')
        self.assertTrue(manifest['originals_match'])
        self.assertTrue(manifest['schema_exports_match'])
        self.assertTrue(manifest['report_matches_strict_inputs'])
        self.assertEqual(manifest['files'], manifest['strict_input_hashes'])
        self.assertEqual({name: value for name, value in manifest['files'].items() if name != self.current},
                         manifest['acquired_input_hashes'])
        self.assertEqual(set(manifest['schema_exports']), set(build.ROOM_SCHEMA_COLLECTION_PHASES))
        self.assertEqual(manifest['writer_schema_export']['sha256'], manifest['files'][self.current])
        self.assertFalse(manifest['accepted'])
        self.assertFalse(manifest['apk_exported'])
        self.assertFalse((self.root / 'artifacts').exists())

