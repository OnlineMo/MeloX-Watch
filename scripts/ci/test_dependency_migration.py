    def test_invalid_request_types_preimages_tools_and_missing_old_inputs_never_fallback(self):
        original = copy.deepcopy(self.request)
        changes = [('schema_version', True), ('schema_version', 1.0), ('owner_id', 143324986.0),
                   ('base_source_sha', 'invalid'), ('diagnostic_android_test', 0),
                   ('current_schema', self.old), ('reviewed_input_hashes', {}),
                   ('frozen_input_hashes', {}), ('migration_tool_hashes', {}),
                   ('allowed_dependency_outputs', [])]
        for key, value in changes:
            with self.subTest(key=key, value=value):
                self.request = copy.deepcopy(original)
                self.request[key] = value
                self.save_request()
                with self.assertRaises(ValueError):
                    build.build('debug')
                self.process.assert_not_called()
        self.request = original
        self.save_request()
        for name in ('gradle/verification-metadata.xml', 'app/gradle.lockfile', self.old):
            path = self.android / name
            data = path.read_bytes()
            path.unlink()
            try:
                with self.subTest(name=name), self.assertRaises(ValueError):
                    build.build('debug')
                self.process.assert_not_called()
            finally:
                path.write_bytes(data)
        self.bootstrap_dependencies.assert_not_called()
        self.bootstrap_room_schema.assert_not_called()

