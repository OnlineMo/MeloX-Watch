    def test_every_natural_failure_and_timeout_stops_preserving_the_exact_error_without_export(self):
        original = self.acquire
        for index, name in enumerate(build.DEPENDENCY_MIGRATION_PHASES):
            for failure in (subprocess.CalledProcessError(13, ['mock-gradle']),
                            BuildTimeout(['mock-gradle'], name, 'phase deadline', 1200),
                            BuildTimeout(['mock-gradle'], name, 'no build output', 300),
                            BuildTimeout(['mock-gradle'], name, 'total build deadline', 2700)):
                with self.subTest(phase=name, failure=type(failure).__name__):
                    # Every case owns a new local-safe report fixture, never a real Gradle process.
                    self.reset_outputs()
                    def fail(command, **kwargs):
                        original(command, **kwargs)
                        if kwargs['phase'] == name:
                            raise failure
                    self.process.reset_mock(side_effect=True)
                    self.process.side_effect = fail
                    with self.assertRaises(type(failure)) as raised:
                        build.build('debug')
                    self.assertIs(raised.exception, failure)
                    self.assertEqual(self.process.call_count, index + 1)
                    self.assertEqual(self.manifest()['status'], 'failed-partial')
                    self.assertFalse(self.manifest()['apk_exported'])
        self.inspect_apk.assert_not_called()

    def reset_outputs(self):
        import shutil
        report = self.android / build.ROOM_SCHEMA_REPORT_DIRECTORY
        if report.exists():
            self.assertTrue(report.resolve().is_relative_to(self.root.resolve()))
            shutil.rmtree(report)
        (self.android / self.current).unlink(missing_ok=True)
        self.write('android/gradle/verification-metadata.xml', XML)
        self.write('android/app/gradle.lockfile', b'fixture:library:1=oldCompile\nempty=lintChecks\n')

    def test_graph_only_missing_compile_runtime_or_plugin_bytes_stop_before_strict(self):
        for missing in ('graph-only', ':app:compileWatchAndroidDebugKotlin', ':app:testWatchAndroidDebugUnitTest',
                        ':app:bundledSqliteHost', ':buildscript:classpath', 'test-actions', 'float-run', 'fake-coordinate'):
            with self.subTest(missing=missing):
                self.reset_outputs()
                def invalidate(command, **kwargs):
                    self.acquire(command, **kwargs)
                    path = self.android / build.ROOM_SCHEMA_REPORT_DIRECTORY / build.DEPENDENCY_ACQUISITION_FILE
                    record = json.loads(path.read_bytes())
                    if missing == 'graph-only':
                        record['consumers'] = []
                    elif missing == 'test-actions':
                        record['test_task_count'] = 1
                    elif missing == 'float-run':
                        record['run_attempt'] = 2.0
                    elif missing == 'fake-coordinate':
                        entry = next(value for value in record['consumers'] if value['id'] == ':app:bundledSqliteHost')
                        entry['files'][0]['component'][2] = '2.6.1'
                    else:
                        entry = next(value for value in record['consumers'] if value['id'] == missing)
                        entry['files'] = []
                        if 'file_count' in entry:
                            entry['file_count'] = 0
                    path.write_text(json.dumps(record) + '\n', encoding='utf-8')
                self.process.reset_mock(side_effect=True)
                self.process.side_effect = invalidate
                with self.assertRaises(ValueError):
                    build.build('debug')
                self.assertEqual(self.process.call_count, 1)
                self.assertEqual(self.manifest()['status'], 'failed-partial')

    def test_writer_cannot_delete_old_pins_rebind_old_lock_or_change_old_schema(self):
        for changed in ('pin', 'lock', 'schema'):
            with self.subTest(changed=changed):
                self.reset_outputs()
                def mutate(command, **kwargs):
                    self.acquire(command, **kwargs)
                    if changed == 'pin':
                        path = self.android / 'gradle/verification-metadata.xml'
                        path.write_bytes(path.read_bytes().replace(b'e' * 64, b'f' * 64))
                    elif changed == 'lock':
                        path = self.android / 'app/gradle.lockfile'
                        path.write_bytes(path.read_bytes().replace(b'fixture:library:1=oldCompile', b'fixture:library:2=oldCompile'))
                    else:
                        self.write('android/' + self.old, b'{"drift":1}\n')
                self.process.reset_mock(side_effect=True)
                self.process.side_effect = mutate
                with self.assertRaises(ValueError):
                    build.build('debug')
                self.assertEqual(self.process.call_count, 1)
                if changed == 'schema':
                    self.write('android/' + self.old, b'{"old":1}\n')

    def test_strict_dependency_schema_witness_and_frozen_source_drift_stop_later_calls(self):
        for index, phase in enumerate(build.ROOM_SCHEMA_COLLECTION_PHASES, 1):
            for changed in ('dependency', 'schema', 'extra-schema', 'witness', 'source'):
                with self.subTest(phase=phase, changed=changed):
                    self.reset_outputs()
                    source = self.root / 'version.properties'
                    source_bytes = source.read_bytes()
                    def mutate(command, **kwargs):
                        self.acquire(command, **kwargs)
                        if kwargs['phase'] == phase:
                            if changed == 'dependency':
                                path = self.android / 'app/gradle.lockfile'
                                path.write_bytes(path.read_bytes() + b'new:drift:1=drift\n')
                            elif changed == 'schema':
                                self.write('android/' + self.current, b'{"different":true}\n')
                            elif changed == 'extra-schema':
                                self.write('android/' + build.ROOM_SCHEMA_DIRECTORY + '/9.json', b'{"extra":9}\n')
                            elif changed == 'witness':
                                path = self.android / build.ROOM_SCHEMA_REPORT_DIRECTORY / build.DEPENDENCY_ACQUISITION_FILE
                                path.write_bytes(path.read_bytes() + b' ')
                            else:
                                source.write_bytes(source_bytes + b'changed\n')
                    self.process.reset_mock(side_effect=True)
                    self.process.side_effect = mutate
                    with self.assertRaises(ValueError):
                        build.build('debug')
                    self.assertEqual(self.process.call_count, index + 1)
                    self.assertEqual(self.manifest()['status'], 'failed-partial')
                    source.write_bytes(source_bytes)
                    (self.android / build.ROOM_SCHEMA_DIRECTORY / '9.json').unlink(missing_ok=True)

    def test_report_link_drift_cannot_replace_natural_failure_or_timeout(self):
        report = self.android / build.ROOM_SCHEMA_REPORT_DIRECTORY
        original = Path.is_symlink
        for failure in (subprocess.CalledProcessError(7, ['mock-gradle']),
                        BuildTimeout(['mock-gradle'], 'migration-acquire', 'phase deadline', 1200)):
            self.reset_outputs()
            linked = False
            def fail(command, **kwargs):
                nonlocal linked
                linked = True
                raise failure
            self.process.reset_mock(side_effect=True)
            self.process.side_effect = fail
            with patch.object(Path, 'is_symlink', lambda path: (linked and path == report.parent) or original(path)):
                with self.assertRaises(type(failure)) as raised:
                    build.build('debug')
                self.assertIs(raised.exception, failure)
                self.assertEqual(raised.exception.__notes__, ['Dependency migration report preservation failed'])

