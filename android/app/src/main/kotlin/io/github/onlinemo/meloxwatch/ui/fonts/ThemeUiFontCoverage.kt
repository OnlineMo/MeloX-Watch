/**
 * A frozen, bounded capture of currently visible dynamic titles, artists, list cells and notices.
 * This is a UI-text bound, not a library-size cap. Reject before copying oversized lists or text;
 * callers must not pass the full library or retain private corpus text in logs or diagnostics.
 */
class ThemeUiFontText private constructor(
    internal val parts: List<String>,
    val issue: LyricsFontIssue?,
) {
    companion object {
        private const val MAX_VISIBLE_PARTS = 1024

        fun capture(visibleParts: List<String>): ThemeUiFontText {
            if (visibleParts.size > MAX_VISIBLE_PARTS) return rejected(LyricsFontIssue.INVALID_INPUT)
            return try {
                val owned = ArrayList<String>(visibleParts.size)
                var units = 0
                for (part in visibleParts) {
                    if (owned.size == MAX_VISIBLE_PARTS || part.length > LyricsFontLimits.TEXT_CHARACTERS - units) {
                        return rejected(LyricsFontIssue.INVALID_INPUT)
                    }
                    units += part.length
                    owned.add(part)
                }
                ThemeUiFontText(Collections.unmodifiableList(owned), null)
            } catch (_: ConcurrentModificationException) { rejected(LyricsFontIssue.INVALID_INPUT) }
            catch (_: OutOfMemoryError) { rejected(LyricsFontIssue.LOW_MEMORY) }
        }

        private fun rejected(issue: LyricsFontIssue): ThemeUiFontText = ThemeUiFontText(emptyList(), issue)
    }
}

/**
 * Localized labels/actions/errors/licenses are real resource text, not preview samples. Format
 * strings are read without formatting; digits and locale-specific separators cover changing
 * counts/clocks without recreating a font binding on every media tick. Dynamic displayed text
 * is supplied by the caller and must include actual title/artist/list/notice text and licenses.
 */
suspend fun themeUiFontCoverage(
    resources: Resources,
    currentText: ThemeUiFontText,
    visibleNow: () -> Boolean,
): LyricsFontPreviewText = withContext(Dispatchers.Default) {
    fontCoverageCheckpoint(visibleNow)
    currentText.issue?.let { throw LyricsFontException(it) }
    val text = FontCoverageBuilder()
    text.append("0123456789 +-.,:/()%")
    val locale = if (resources.configuration.locales.isEmpty) Locale.ROOT else resources.configuration.locales[0]
    val numbers = NumberFormat.getNumberInstance(locale)
    for (digit in 0..9) text.append(numbers.format(digit.toLong()))
    text.append(numbers.format(-1234567.89))
    for ((index, id) in UI_STRING_IDS.withIndex()) {
        if (index % RESOURCE_BATCH == 0) fontCoverageCheckpoint(visibleNow)
        text.append(resources.getString(id))
    }
    for (id in UI_PLURAL_IDS) {
        fontCoverageCheckpoint(visibleNow)
        // Android chooses the current locale's zero/one/other path; no raw XML language bypass.
        for (quantity in intArrayOf(0, 1, 2)) text.append(resources.getQuantityString(id, quantity))
    }
    for ((index, part) in currentText.parts.withIndex()) {
        if (index % RESOURCE_BATCH == 0) fontCoverageCheckpoint(visibleNow)
        text.append(part)
    }
    fontCoverageCheckpoint(visibleNow)
    val complete = text.finish()
    // Both UI roles may display any of this text. They share one immutable corpus, not face caches.
    LyricsFontPreviewText(complete, complete)
}

