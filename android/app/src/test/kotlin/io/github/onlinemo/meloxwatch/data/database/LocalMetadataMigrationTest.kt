package io.github.onlinemo.meloxwatch.data.database

import android.content.Context
import android.database.sqlite.SQLiteDatabase
import androidx.room.Room
import androidx.room.migration.Migration
import androidx.sqlite.SQLiteConnection
import androidx.sqlite.db.SupportSQLiteDatabase
import androidx.sqlite.db.SupportSQLiteOpenHelper
import androidx.sqlite.db.framework.FrameworkSQLiteOpenHelperFactory
import androidx.sqlite.driver.bundled.BundledSQLiteDriver
import io.github.onlinemo.meloxwatch.data.lyrics.store.LyricsRoomRows
import java.io.File
import kotlinx.coroutines.runBlocking
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.RuntimeEnvironment
import org.robolectric.annotation.Config
import org.robolectric.annotation.SQLiteMode

/** Historical structure and cells come from the preserved cloud v8 export; v9 must be generated by Room. */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [26], manifest = Config.NONE)
@SQLiteMode(SQLiteMode.Mode.NATIVE)
class LocalMetadataMigrationTest {
    @get:Rule val temporary = TemporaryFolder()
    private val context get() = RuntimeEnvironment.getApplication() as Context
    private val schema by lazy { FrozenRoomSchemaTestFixture.load("/database/melox-schema-8.json", 8,
        "a866f695958dfe9c93a2a9af560d252c3651eb504628e9100939465acb4da6f0", OLD_IDENTITY) }

    @Test(timeout = 30_000L)
    fun generatedV9PreservesAllV8CellsAndIndexesAndStartsWithoutAnyAssociation() = runBlocking {
        val file = File(temporary.root, "metadata-v8-to-v9.db")
        val before = seed(file)
        val current = open(file)
        try { assertCurrent(current, before) } finally { current.close() }
        val reopened = open(file)
        try { assertCurrent(reopened, before) } finally { reopened.close() }
    }

    @Test(timeout = 30_000L)
    fun supportMigrationAddsOnlyTheAssociationTableAndIndexesWithoutRewritingTheOldMaster() = runBlocking {
        val file = File(temporary.root, "metadata-support.db")
        val before = seed(file)
        val helper = supportOpen(file)
        try {
            val database = helper.writableDatabase
            assertEquals(9, database.version)
            schema.assertRowsPreserved(before.rows) { database.query(it) }
            assertEquals(before.catalog, catalog { database.query(it) })
            database.query(IDENTITY).use { rows -> assertTrue(rows.moveToFirst()); assertEquals(OLD_IDENTITY, rows.getString(0)) }
            database.query("SELECT COUNT(*) FROM local_metadata_associations").use { rows -> assertTrue(rows.moveToFirst()); assertEquals(0L, rows.getLong(0)) }
            database.query("PRAGMA foreign_key_list(local_metadata_associations)").use { rows ->
                assertTrue(rows.moveToFirst())
                assertEquals("local_tracks", rows.getString(rows.getColumnIndexOrThrow("table")))
                assertEquals("trackId", rows.getString(rows.getColumnIndexOrThrow("from")))
                assertEquals("RESTRICT", rows.getString(rows.getColumnIndexOrThrow("on_delete")))
                assertFalse(rows.moveToNext())
            }
            database.query("PRAGMA index_list(local_metadata_associations)").use { rows ->
                val names = mutableSetOf<String>()
                while (rows.moveToNext()) names += rows.getString(rows.getColumnIndexOrThrow("name"))
                assertTrue("index_local_metadata_associations_trackId" in names)
                assertTrue("index_local_metadata_associations_assetId_purpose" in names)
            }
            database.query("PRAGMA foreign_key_check").use { assertFalse(it.moveToFirst()) }
        } finally { helper.close() }
    }

    @Test(timeout = 30_000L)
    fun failureAfterTheLastIndexRollsBackAllNewObjectsVersionAndEveryHistoricalCellForBothDrivers() = runBlocking {
        for (support in listOf(false, true)) {
            val file = File(temporary.root, "metadata-rollback-$support.db")
            val before = seed(file)
            var reachedLastIndex = false
            val failure = if (support) {
                val helper = supportOpen(file, fail = true, onMigrated = { database ->
                    database.query(NEW_INDEX_COUNT).use { rows ->
                        assertTrue(rows.moveToFirst()); assertEquals(2L, rows.getLong(0))
                    }
                    reachedLastIndex = true
                })
                try { expectFailure { helper.writableDatabase } } finally { helper.close() }
            } else {
                val last = object : Migration(8, 9) {
                    override fun migrate(connection: SQLiteConnection) {
                        MeloXDatabase.MIGRATION_8_9.migrate(connection)
                        connection.prepare(NEW_INDEX_COUNT).use { rows ->
                            assertTrue(rows.step()); assertEquals(2L, rows.getLong(0))
                        }
                        reachedLastIndex = true
                        throw ControlledFailure()
                    }
                }
                val current = open(file, last)
                try { expectFailure { current.withTestWriterSql { scalarLong("PRAGMA user_version") } } }
                finally { current.close() }
            }
            assertTrue("The controlled failure must occur after both real indexes exist", reachedLastIndex)
            assertTrue("A connection or pre-migration failure cannot establish late rollback",
                generateSequence<Throwable>(failure) { it.cause }.take(16).any { it is ControlledFailure })
            SQLiteDatabase.openDatabase(file.absolutePath, null, SQLiteDatabase.OPEN_READONLY).use { old ->
                assertEquals(8, old.version)
                schema.assertStructure { old.rawQuery(it, null) }
                schema.assertRowsPreserved(before.rows) { old.rawQuery(it, null) }
                assertEquals(before.catalog, catalog { old.rawQuery(it, null) })
                old.rawQuery(IDENTITY, null).use { rows -> assertTrue(rows.moveToFirst()); assertEquals(OLD_IDENTITY, rows.getString(0)) }
            }
            val retried = open(file)
            try { assertCurrent(retried, before) } finally { retried.close() }
        }
    }

    private suspend fun seed(file: File): Before {
        SQLiteDatabase.openOrCreateDatabase(file, null).use { database ->
            database.setForeignKeyConstraintsEnabled(true)
            schema.create(database)
            LyricsRoomRows.seed { table, values ->
                assertTrue(database.insertOrThrow(table, null, values) >= 0L)
            }
            database.version = 8
            return Before(schema.snapshotRows { database.rawQuery(it, null) }, catalog { database.rawQuery(it, null) })
        }
    }

    private fun open(file: File, last: Migration = MeloXDatabase.MIGRATION_8_9): MeloXDatabase = Room.databaseBuilder(
        context, MeloXDatabase::class.java, file.absolutePath,
    ).setDriver(BundledSQLiteDriver()).addMigrations(last).build()

    private fun supportOpen(file: File, fail: Boolean = false,
        onMigrated: (SupportSQLiteDatabase) -> Unit = {}): SupportSQLiteOpenHelper =
        FrameworkSQLiteOpenHelperFactory().create(SupportSQLiteOpenHelper.Configuration.builder(context)
            .name(file.absolutePath).callback(object : SupportSQLiteOpenHelper.Callback(9) {
                override fun onCreate(db: SupportSQLiteDatabase) = throw AssertionError("The historical file is required")
                override fun onUpgrade(db: SupportSQLiteDatabase, oldVersion: Int, newVersion: Int) {
                    assertEquals(8, oldVersion); assertEquals(9, newVersion)
                    MeloXDatabase.MIGRATION_8_9.migrate(db)
                    onMigrated(db)
                    if (fail) throw ControlledFailure()
                }
            }).build())

    private suspend fun assertCurrent(current: MeloXDatabase, before: Before) = current.withTestWriterSql {
        schema.assertRowsPreserved(before.rows, this)
        assertEquals(9L, scalarLong("PRAGMA user_version"))
        assertEquals(0L, scalarLong("SELECT COUNT(*) FROM local_metadata_associations"))
        assertEquals("ok", scalarText("PRAGMA integrity_check"))
        query("PRAGMA foreign_key_check") { assertFalse(it.step()) }
        assertTrue(scalarText(IDENTITY) != OLD_IDENTITY)
        assertEquals(before.catalog, query(CATALOG) { rows -> buildList { while (rows.step()) add(rows.getText(0)) } })
        assertEquals(schema.tableNames.size.toLong() + 1L, scalarLong("SELECT COUNT(*) FROM sqlite_master WHERE type='table' " +
            "AND name NOT LIKE 'sqlite_%' AND name NOT IN ('room_master_table','android_metadata')"))
    }

    private fun catalog(query: (String) -> android.database.Cursor): List<String> = query(CATALOG).use { rows ->
        buildList { while (rows.moveToNext()) add(rows.getString(0)) }
    }
    private suspend fun expectFailure(action: suspend () -> Any?): Exception {
        try { action() } catch (failure: Exception) { return failure }
        throw AssertionError("A failed migration committed")
    }
    private class ControlledFailure : RuntimeException("Controlled metadata migration failure")
    private data class Before(val rows: Map<String, FrozenTableRows>, val catalog: List<String>)
    private companion object {
        const val OLD_IDENTITY = "174b802d05d8f0efe5d947b4e5dc7fc2"
        const val IDENTITY = "SELECT identity_hash FROM room_master_table WHERE id=42"
        const val NEW_INDEX_COUNT = "SELECT COUNT(*) FROM sqlite_master WHERE type='index' " +
            "AND tbl_name='local_metadata_associations' AND name IN " +
            "('index_local_metadata_associations_trackId','index_local_metadata_associations_assetId_purpose')"
        const val CATALOG = "SELECT sql FROM sqlite_master WHERE name NOT LIKE 'sqlite_%' " +
            "AND name NOT IN ('room_master_table','android_metadata') AND tbl_name != 'local_metadata_associations' ORDER BY type,name"
    }
}
